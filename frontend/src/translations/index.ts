export function getTranslation(lang: string, key: keyof TranslationStrings): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['hi'] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || '';
}

